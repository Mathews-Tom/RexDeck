from rexdeck.runtime import RuntimePaths, verify_runtime

_BEGIN = b"-- BEGIN REXDECK (owned palette loader)\n"
_END = b"-- END REXDECK\n"
_PALETTE = (
    b"-- Generated by the LazyRex hub. Do not edit: the hub replaces this file.\n"
    b'-- Load it from init.lua with: pcall(require, "lazyrex_palette")\n'
)
_MAX_READ = 2 * 1024 * 1024
_COMMAND_WAIT = 8.0
_START_WAIT = 20.0
_STOP_WAIT = 12.0


@dataclass(frozen=True)
class Setup:
    project: Path
    workspace: Path
    config: Path
    server: str
    real_server: bool = False


@dataclass(frozen=True)
class _Paths:
    project: Path
    workspace: Path
    selected: Path
    config: Path
    palette: Path
    hub: Path
    state: Path
    receipt: Path


@dataclass(frozen=True)
class _File:
    data: bytes | None
    mode: int


@dataclass(frozen=True)
class _Change:
    path: Path
    before: _File
    after: bytes | None
    loader: bool = False


@dataclass(frozen=True)
class _Hub:
    client: str
    pid: int
    generation: str


@dataclass(frozen=True)
class _Result:
    code: int
    output: bytes


def _paths(setup: Setup) -> _Paths:
    if not setup.server.strip() or setup.server != setup.server.strip():
        raise RuntimeError("An explicit nonempty Rex server endpoint is required")
    socket = _socket_path(setup.server)
    if not setup.real_server and not any(
        socket.is_relative_to(root.resolve())
        for root in (Path("/tmp"), Path("/private/tmp"))
    ):
        raise RuntimeError(
            "Isolated endpoints must be Unix sockets under /tmp or /private/tmp; "
            "the unchanged renderer refuses other lab paths. Use --real-server "
            "only for an explicitly approved real-server application."
        )
    try:
        selected = setup.config.absolute()
        config = selected.resolve(strict=True)
        if not config.is_file():
            raise RuntimeError(f"Selected Rex config is not a regular file: {config}")
        project = setup.project.resolve(strict=True)
        workspace = setup.workspace.resolve()
        state = workspace / "hub-state"
        if state.is_symlink() or (state.exists() and not state.is_dir()):
            raise RuntimeError(
                f"Owned hub state must be a real directory, not a symlink: {state}"
            )
    except OSError as exc:
        raise RuntimeError(f"Cannot resolve the explicit setup paths: {exc}") from exc
    return _Paths(
        project,
        workspace,
        selected,
        config,
        config.parent / "rexdeck_palette.lua",
        workspace / "hub.json",
        workspace / "hub-state",
        workspace / "setup.json",
    )


def _socket_path(endpoint: str) -> Path:
    if not endpoint.startswith("unix://"):
        raise RuntimeError(
            "The unchanged runtime requires an explicit unix:// socket endpoint"
        )
    try:
        decoded = unquote(endpoint[len("unix://") :], errors="strict")
        path = Path(decoded)
        if not path.is_absolute() or "\x00" in decoded:
            raise RuntimeError("Rex Unix socket endpoint must name an absolute path")
        return path.resolve()
    except (OSError, UnicodeError) as exc:
        raise RuntimeError(
            f"Cannot resolve the selected Rex socket endpoint: {exc}"
        ) from exc


def _server_status(setup: Setup, *, selected: bool) -> dict[str, object] | None:
    argv = [_executable("rex"), "--autostart=false", "--timeout", "3s"]
    if selected:
        argv += ["-S", setup.server]
    result = _run([*argv, "server", "status", "--json"], _env(setup))
    if result.code != 0:
        detail = result.output.decode(errors="replace")
        if not selected and "rex server is not running" in detail:
            return None
        raise RuntimeError(
            f"Cannot prove selected/default Rex endpoint isolation: {detail.strip()}"
        )
    value = _decode(result.output, "Rex server status")
    if (
        not isinstance(value.get("endpoint"), str)
        or not value["endpoint"]
        or not isinstance(value.get("instance_id"), str)
        or not value["instance_id"]
    ):
        raise RuntimeError(
            "Rex server status lacks endpoint/instance identity; refusing an uncertain server"
        )
    return value


def _endpoint_policy(setup: Setup) -> None:
    selected = _socket_path(setup.server)
    known = [
        Path.home() / "Library/Application Support/rex/server.sock",
        Path("/run/user") / str(os.getuid()) / "rex/server.sock",
    ]
    xdg = os.environ.get("XDG_RUNTIME_DIR")
    if xdg and Path(xdg).is_absolute():
        known.append(Path(xdg) / "rex/server.sock")
    is_real = selected in [path.resolve() for path in known]
    is_real = is_real or str(selected).endswith(
        "/Library/Application Support/rex/server.sock"
    )
    is_real = is_real or (
        selected.name == "server.sock"
        and selected.parent.name == "rex"
        and selected.parent.parent.parent == Path("/run/user")
        and selected.parent.parent.name.isdecimal()
    )
    if not is_real:
        default = _server_status(setup, selected=False)
        current = _server_status(setup, selected=True)
        assert current is not None
        if _socket_path(cast(str, current["endpoint"])) != selected:
            raise RuntimeError(
                "Selected server answered with a different socket endpoint"
            )
        if default is not None:
            is_real = (
                _socket_path(cast(str, default["endpoint"])) == selected
                or default["instance_id"] == current["instance_id"]
            )
    if is_real != setup.real_server:
        raise RuntimeError(
            "Selected endpoint is the real Rex server; explicit --real-server approval is required"
            if is_real
            else "--real-server was selected for an isolated server; remove the flag"
        )


def _env(setup: Setup) -> dict[str, str]:
    result = {
        k: v
        for k, v in os.environ.items()
        if k not in {"REX_SESSION", "REX_BLOCK", "REX_CLIENT", "REX_SERVER"}
    }
    result["REX_CONFIG"] = str(setup.config.absolute())
    return result


def _executable(name: str) -> str:
    found = shutil.which(name)
    if found is None:
        raise RuntimeError(
            f"Required executable not found: {name}; install it before applying or starting"
        )
    return str(Path(found).absolute())


def _run(
    argv: list[str], env: dict[str, str], *, timeout: float = _COMMAND_WAIT
) -> _Result:
    """Bound both output allocation and the lifetime of every helper command."""
    try:
        child = subprocess.Popen(
            argv,
            env=env,
            stdin=subprocess.DEVNULL,
            stdout=subprocess.PIPE,
            stderr=subprocess.STDOUT,
        )
    except OSError as exc:
        raise RuntimeError(f"Cannot execute {argv[0]}: {exc}") from exc
    assert child.stdout is not None
    output = bytearray()
    deadline = time.monotonic() + timeout
    try:
        with selectors.DefaultSelector() as selector:
            selector.register(child.stdout, selectors.EVENT_READ)
            while selector.get_map():
                remaining = deadline - time.monotonic()
                if remaining <= 0:
                    raise RuntimeError(
                        f"Command timed out: {argv[0]} {' '.join(argv[1:])}"
                    )
                for key, _ in selector.select(remaining):
                    chunk = os.read(key.fd, min(65536, _MAX_READ + 1 - len(output)))
                    if not chunk:
                        selector.unregister(child.stdout)
                    else:
                        output.extend(chunk)
                        if len(output) > _MAX_READ:
                            raise RuntimeError(
                                f"Command output exceeds {_MAX_READ} bytes: {argv[0]}"
                            )
        code = child.wait(timeout=max(0.01, deadline - time.monotonic()))
        return _Result(code, bytes(output))
    except (RuntimeError, OSError, subprocess.TimeoutExpired) as exc:
        child.kill()
        child.wait(timeout=2)
        if isinstance(exc, RuntimeError):
            raise
        raise RuntimeError(
            f"Command failed or exceeded its deadline: {argv[0]}: {exc}"
        ) from exc
    finally:
        child.stdout.close()


def _object(value: object, context: str) -> dict[str, object]:
    if not isinstance(value, dict) or any(not isinstance(key, str) for key in value):
        raise RuntimeError(f"Expected a JSON object in {context}")
    return cast(dict[str, object], value)


def _list(value: object, context: str) -> list[object]:
    if not isinstance(value, list):
        raise RuntimeError(f"Expected a JSON list in {context}")
    return cast(list[object], value)


def _decode(data: bytes, context: str) -> dict[str, object]:
    try:
        value: object = json.loads(data)
    except (ValueError, UnicodeError) as exc:
        raise RuntimeError(f"Invalid JSON in {context}: {exc}") from exc
    return _object(value, context)


def _json(value: object) -> bytes:
    return (
        json.dumps(value, ensure_ascii=False, indent=2, sort_keys=True) + "\n"
    ).encode()


def _rex(setup: Setup, *args: str) -> dict[str, object]:
    result = _run(
        [
            _executable("rex"),
            "-S",
            setup.server,
            "--autostart=false",
            "--timeout",
            "3s",
            *args,
        ],
        _env(setup),
    )
    if result.code != 0:
        raise RuntimeError(
            f"rex {' '.join(args)} failed ({result.code}): "
            f"{result.output.decode(errors='replace').strip()}"
        )
    return _decode(result.output, f"rex {' '.join(args)}")


def _check(setup: Setup) -> None:
    result = _rex(setup, "config", "check", "--json")
    if result.get("diagnostics"):
        raise RuntimeError(f"Selected Rex config was rejected: {result['diagnostics']}")


def _reload(setup: Setup) -> None:
    result = _rex(setup, "config", "reload", "--json")
    if result.get("diagnostics"):
        raise RuntimeError(
            f"Selected Rex config reload was rejected: {result['diagnostics']}"
        )


def _file(path: Path) -> _File:
    try:
        info = path.lstat()
        if not stat.S_ISREG(info.st_mode):
            raise RuntimeError(
                f"Refusing nonregular or symlinked owned artifact: {path}"
            )
        with path.open("rb") as stream:
            data = stream.read(_MAX_READ + 1)
        if len(data) > _MAX_READ:
            raise RuntimeError(f"Owned file exceeds {_MAX_READ} bytes: {path}")
        return _File(data, stat.S_IMODE(info.st_mode))
    except FileNotFoundError:
        return _File(None, 0o600)
    except OSError as exc:
        raise RuntimeError(f"Cannot read {path}: {exc}") from exc


def _replace(
    path: Path, before: _File, after: bytes | None, *, mode: int | None = None
) -> None:
    if _file(path) != before:
        raise RuntimeError(
            f"Concurrent edit or mode change at {path}; nothing overwritten"
        )
    if after is None:
        path.unlink()
        return
    temporary: Path | None = None
    try:
        with tempfile.NamedTemporaryFile(dir=path.parent, delete=False) as stream:
            temporary = Path(stream.name)
            stream.write(after)
            stream.flush()
            os.fsync(stream.fileno())
            os.fchmod(stream.fileno(), before.mode if mode is None else mode)
        if _file(path) != before:
            raise RuntimeError(f"Concurrent edit at {path}; nothing overwritten")
        os.replace(temporary, path)
    except OSError as exc:
        raise RuntimeError(f"Cannot atomically write {path}: {exc}") from exc
    finally:
        if temporary is not None:
            temporary.unlink(missing_ok=True)


def _digest(data: bytes | None) -> str:
    return hashlib.sha256(data).hexdigest() if data is not None else ""


def _loader(paths: _Paths) -> bytes:
    # Lua accepts JSON string escapes except \u; keep UTF-8 paths literal.
    encoded = json.dumps(str(paths.palette), ensure_ascii=False)
    return (
        _BEGIN
        + (
            f"do local ok, err = pcall(dofile, {encoded}); "
            "if not ok then rex.log('warn', 'RexDeck palette unavailable: ' .. tostring(err)) end end\n"
        ).encode()
        + _END
    )


def _without_loader(
    data: bytes, loader: bytes, *, remove_separator: bool = False
) -> bytes:
    if data.count(_BEGIN) != 1 or data.count(_END) != 1 or data.count(loader) != 1:
        raise RuntimeError(
            "RexDeck loader changed or is ambiguous; preserve it for manual reconciliation"
        )
    prefix, _, tail = data.partition(loader)
    # A separator still belongs to the user's config when a later statement needs it.
    if remove_separator and not tail and prefix.endswith(b"\n"):
        prefix = prefix[:-1]
    return prefix + tail


def _receipt(paths: _Paths, setup: Setup) -> dict[str, object] | None:
    snapshot = _file(paths.receipt)
    if snapshot.data is None:
        return None
    result = _decode(snapshot.data, str(paths.receipt))
    expected: dict[str, object] = {
        "version": 1,
        "project": str(paths.project),
        "workspace": str(paths.workspace),
        "config": str(paths.selected),
        "config_target": str(paths.config),
        "server": setup.server,
        "real_server": setup.real_server,
    }
    if any(result.get(key) != value for key, value in expected.items()):
        raise RuntimeError(
            "Setup receipt belongs to another config, target, project, workspace or endpoint"
        )
    if not isinstance(result.get("enabled"), bool):
        raise RuntimeError("Setup receipt has no explicit enabled state")
    for key in ("hub_sha256", "palette_sha256"):
        digest = result.get(key)
        if not isinstance(digest, str) or len(digest) != 64:
            raise RuntimeError(f"Setup receipt has malformed {key}")
    for key in ("hub_mode", "palette_mode"):
        mode = result.get(key)
        if (
            not isinstance(mode, int)
            or isinstance(mode, bool)
            or not 0 <= mode <= 0o7777
        ):
            raise RuntimeError(f"Setup receipt has malformed {key}")
    return result


def _owned_config(paths: _Paths, receipt: dict[str, object]) -> None:
    hub = _file(paths.hub)
    if _digest(hub.data) != receipt.get("hub_sha256") or hub.mode != receipt.get(
        "hub_mode"
    ):
        raise RuntimeError(
            f"Owned hub config changed or is missing: {paths.hub}; inspect before starting"
        )
    data = _file(paths.config).data
    if data is None:
        raise RuntimeError(f"Selected config disappeared: {paths.config}")
    _without_loader(data, _loader(paths))


def _process(pid: int) -> str | None:
    if pid <= 0:
        raise RuntimeError("Invalid owned hub PID")
    try:
        reaped, _ = os.waitpid(pid, os.WNOHANG)
    except ChildProcessError:
        reaped = 0
    if reaped == pid:
        return None
    result = _run(
        ["/bin/ps", "-ww", "-p", str(pid), "-o", "lstart=", "-o", "command="],
        dict(os.environ),
        timeout=2,
    )
    if result.code == 1 and not result.output.strip():
        return None
    if result.code != 0:
        raise RuntimeError(
            f"Cannot inspect hub process {pid}: {result.output.decode(errors='replace')}"
        )
    line = result.output.decode(errors="strict").strip()
    if not line:
        return None
    return line


def _launch(receipt: dict[str, object]) -> dict[str, object] | None:
    value = receipt.get("launch")
    return None if value is None else _object(value, "launch ownership receipt")


def _verified_pid(receipt: dict[str, object]) -> int | None:
    launch = _launch(receipt)
    if launch is None:
        return None
    pid = launch.get("pid")
    identity = launch.get("identity")
    argv = _list(launch.get("argv"), "launch argv")
    if (
        not isinstance(pid, int)
        or isinstance(pid, bool)
        or not isinstance(identity, str)
    ):
        raise RuntimeError("Owned hub launch identity is malformed")
    if any(not isinstance(arg, str) for arg in argv):
        raise RuntimeError("Owned hub argv is malformed")
    if not identity.endswith(" ".join(cast(list[str], argv))):
        raise RuntimeError("Owned hub launch identity does not match its argv")
    current = _process(pid)
    if current != identity:
        return None  # The original writer is gone; never signal a reused PID.
    return pid


def _hubs(setup: Setup, paths: _Paths, receipt: dict[str, object] | None) -> list[_Hub]:
    _endpoint_policy(setup)
    listing = _rex(setup, "client", "ls", "--json")
    clients = _list(listing.get("clients"), "Rex client listing")
    ids: list[str] = []
    for item in clients:
        row = _object(item, "Rex client")
        info_value = row.get("info")
        if info_value is None:
            continue  # Rex permits clients that declare no identifying metadata.
        info = _object(info_value, "Rex client info")
        if (
            info.get("label") == "lazyrex-hub"
            and row.get("connection_state") == "connected"
        ):
            client = row.get("client_id")
            if not isinstance(client, str) or not client:
                raise RuntimeError("Connected LazyRex hub has no client identity")
            ids.append(client)
    if len(ids) > 1:
        raise RuntimeError(
            "Multiple connected LazyRex hubs; refusing ambiguous ownership before writes"
        )
    hubs: list[_Hub] = []
    for client in ids:
        info = _rex(setup, "-C", client, "do", "hub.info")
        pid, generation = info.get("pid"), info.get("generation")
        if (
            receipt is None
            or info.get("state") != str(paths.state.resolve())
            or not isinstance(pid, int)
            or isinstance(pid, bool)
            or not isinstance(generation, str)
            or not generation
            or _verified_pid(receipt) != pid
        ):
            raise RuntimeError(
                f"Foreign or unverifiable LazyRex hub {client}; no setup or competing start permitted"
            )
        hubs.append(_Hub(client, pid, generation))
    return hubs


def _tools() -> dict[str, str]:
    return {
        "python": str(Path(sys.executable).absolute()),
        "rex": _executable("rex"),
        "bat": _executable("bat"),
        "less": _executable("less"),
    }


def _validate_files(paths: _Paths) -> None:
    source = paths.project / "plugins" / "files"
    manifest = _file(source / "lazyrex.json").data
    if manifest is None:
        raise RuntimeError(f"Selected Files source is missing its manifest: {source}")
    value = _decode(manifest, "Files manifest")
    main = value.get("main")
    if value.get("name") != "rexdeck_files" or not isinstance(main, str):
        raise RuntimeError(f"Selected source is not the RexDeck Files plugin: {source}")
    entry = (source / main).resolve()
    if not entry.is_relative_to(source.resolve()) or not entry.is_file():
        raise RuntimeError(
            f"Files manifest main is missing or escapes its source: {entry}"
        )


def _hub_config(
    setup: Setup, paths: _Paths, runtime: RuntimePaths, tools: dict[str, str]
) -> bytes:
    return _json(
        {
            "server": setup.server,
            "state": str(paths.state),
            "rex": tools["rex"],
            "view": str(runtime.view),
            "home": "lazyrex",
            "profiles": "",
            "palette_lua": str(paths.palette),
            "plugins": [{"source": str(runtime.source / "plugins" / "lazyrex")}],
        }
    )


def _selection(paths: _Paths) -> tuple[_File, list[object]]:
    current = _file(paths.state / "plugins.json")
    if current.data is None:
        return current, []
    value = _decode(current.data, "managed plugins.json")
    return current, _list(value.get("plugins"), "managed plugins.json plugins")


def _seed(
    setup: Setup, paths: _Paths, tools: dict[str, str], entries: list[object]
) -> bytes:
    source = str(paths.project / "plugins" / "files")
    result = entries.copy()
    found = False
    for item in entries:
        entry = _object(item, "managed plugin entry")
        if entry.get("id") == "files" or entry.get("source") == source:
            if entry.get("id") != "files" or entry.get("source") != source:
                raise RuntimeError(
                    "Managed Files id/source conflicts with an existing selection"
                )
            found = True
    if not found:
        result.append(
            {
                "id": "files",
                "source": source,
                "args": {key: tools[key] for key in ("python", "rex", "bat")}
                | {"server": setup.server},
            }
        )
    return _json({"plugins": result})


@contextmanager
def _defer_sigint() -> Iterator[None]:
    """Finish a short ownership handoff or recovery before delivering Ctrl-C."""
    if threading.current_thread() is not threading.main_thread():
        yield
        return
    interrupted = False

    def defer(_signum: int, _frame: FrameType | None) -> None:
        nonlocal interrupted
        interrupted = True

    previous = signal.signal(signal.SIGINT, defer)
    try:
        yield
    finally:
        signal.signal(signal.SIGINT, previous)
        if interrupted and callable(previous):
            previous(signal.SIGINT, None)


def _rollback(changes: list[_Change]) -> list[str]:
    conflicts: list[str] = []
    for change in reversed(changes):
        try:
            current = _file(change.path)
            # Changes are registered before writing, including a write that raised
            # after its atomic replacement. An unchanged attempt needs no undo.
            if current == change.before:
                continue
            if change.loader and current.data is not None and change.after is not None:
                before_data = change.before.data or b""
                if change.after.startswith(before_data):
                    added = change.after[len(before_data) :]
                    restored = _without_loader(
                        current.data,
                        added.removeprefix(b"\n"),
                        remove_separator=added.startswith(b"\n"),
                    )
                elif current.data.startswith(change.after):
                    restored = before_data + current.data[len(change.after) :]
                else:
                    raise RuntimeError(
                        f"Rollback preserves concurrent config edits: {change.path}"
                    )
                _replace(change.path, current, restored)
            else:
                if current.data != change.after or (
                    change.after is not None and current.mode != change.before.mode
                ):
                    raise RuntimeError(
                        f"Rollback preserves concurrently changed artifact: {change.path}"
                    )
                _replace(
                    change.path, current, change.before.data, mode=change.before.mode
                )
        except RuntimeError as exc:
            conflicts.append(str(exc))
    return conflicts


def _recover_changes(
    setup: Setup,
    changes: list[_Change],
    operation: str,
    cause: RuntimeError | OSError | KeyboardInterrupt,
) -> NoReturn:
    conflicts: list[str] = []
    cancellation: KeyboardInterrupt | None = None
    try:
        with _defer_sigint():
            conflicts = _rollback(changes)
            try:
                _reload(setup)
            except RuntimeError as reload_error:
                conflicts.append(f"Rollback config reload failed: {reload_error}")
    except KeyboardInterrupt as interrupted:
        # A deferred Ctrl-C must not bypass the completed recovery report.
        cancellation = interrupted
    suffix = (
        f"; recovery needs judgment: {'; '.join(conflicts)}"
        if conflicts
        else "; owned changes rolled back"
    )
    if isinstance(cause, KeyboardInterrupt):
        cause.add_note(f"{operation} cancelled{suffix}")
        raise cause
    if cancellation is not None:
        cancellation.add_note(f"{operation} cancelled after failure: {cause}{suffix}")
        raise cancellation from cause
    raise RuntimeError(f"{operation} failed: {cause}{suffix}") from cause


def _apply_changes(
    setup: Setup,
    paths: _Paths,
    planned: list[_Change],
    receipt: dict[str, object],
    receipt_before: _File,
) -> None:
    applied: list[_Change] = []
    try:
        for change in planned:
            if paths.selected.resolve(strict=True) != paths.config:
                raise RuntimeError("Selected Rex config symlink changed during setup")
            applied.append(change)
            _replace(change.path, change.before, change.after)
        _check(setup)
        _reload(setup)
        publication = _Change(paths.receipt, receipt_before, _json(receipt))
        applied.append(publication)
        _replace(publication.path, publication.before, publication.after)
    except (RuntimeError, OSError, KeyboardInterrupt) as exc:
        _recover_changes(setup, applied, "Apply", exc)


def inspect_setup(setup: Setup) -> dict[str, object]:
    paths = _paths(setup)
    receipt = _receipt(paths, setup)
    conflicts: list[str] = []
    prerequisites: dict[str, object] = {}
    try:
        runtime = verify_runtime(paths.project, paths.workspace)
        prerequisites["runtime"] = str(runtime.hub)
    except RuntimeError as exc:
        prerequisites["runtime_error"] = str(exc)
    for name in ("rex", "bat", "less"):
        try:
            prerequisites[name] = _executable(name)
        except RuntimeError as exc:
            prerequisites[f"{name}_error"] = str(exc)
    try:
        hubs = _hubs(setup, paths, receipt)
    except RuntimeError as exc:
        hubs = []
        conflicts.append(str(exc))
    config = _file(paths.config).data or b""
    if receipt is None:
        if paths.state.exists() and next(paths.state.iterdir(), None) is not None:
            conflicts.append(f"Unowned existing hub state: {paths.state}")
        for path in (paths.hub, paths.palette, paths.state / "plugins.json"):
            if _file(path).data is not None:
                conflicts.append(f"Unowned existing artifact: {path}")
        if _BEGIN in config or _END in config:
            conflicts.append("An unowned RexDeck loader already exists")
    elif receipt.get("enabled") is True:
        try:
            _owned_config(paths, receipt)
        except RuntimeError as exc:
            conflicts.append(str(exc))
    _, entries = _selection(paths)
    return {
        "state": "conflict" if conflicts else "inspected",
        "server": setup.server,
        "config": str(paths.selected),
        "config_target": str(paths.config),
        "owned": receipt is not None,
        "enabled": bool(receipt and receipt.get("enabled")),
        "owned_files": [str(paths.hub), str(paths.palette), str(paths.receipt)],
        "loader": _loader(paths).decode(),
        "selected_sources": entries,
        "prerequisites": prerequisites,
        "connected_hubs": [hub.client for hub in hubs],
        "conflicts": conflicts,
    }


def apply_setup(setup: Setup, *, reseed: bool = False) -> dict[str, object]:
    paths = _paths(setup)
    receipt_before = _file(paths.receipt)
    receipt = _receipt(paths, setup)
    hubs = _hubs(
        setup, paths, receipt
    )  # Refuse a competing writer before any filesystem writes.
    if receipt is not None and not hubs and _verified_pid(receipt) is not None:
        raise RuntimeError(
            "Owned hub is still starting or disconnected; stop it before applying"
        )
    runtime = verify_runtime(paths.project, paths.workspace)
    tools = _tools()
    _check(setup)
    config = _file(paths.config)
    assert config.data is not None
    loader = _loader(paths)
    planned: list[_Change] = []
    hub = _hub_config(setup, paths, runtime, tools)
    if receipt is None:
        if paths.state.exists() and next(paths.state.iterdir(), None) is not None:
            raise RuntimeError(
                f"Unowned existing hub state: {paths.state}; use a distinct workspace"
            )
        for path in (paths.hub, paths.palette, paths.state / "plugins.json"):
            if _file(path).data is not None:
                raise RuntimeError(
                    f"Unowned existing artifact: {path}; inspect instead of overwriting"
                )
        if _BEGIN in config.data or _END in config.data:
            raise RuntimeError("Unowned or ambiguous RexDeck loader; nothing changed")
        receipt = {
            "version": 1,
            "project": str(paths.project),
            "workspace": str(paths.workspace),
            "config": str(paths.selected),
            "config_target": str(paths.config),
            "server": setup.server,
            "real_server": setup.real_server,
            "launch": None,
            "loader_separator": ""
            if not config.data or config.data.endswith(b"\n")
            else "\n",
        }
    else:
        if receipt.get("enabled") is True:
            _owned_config(paths, receipt)
        elif _BEGIN in config.data or _END in config.data:
            raise RuntimeError(
                "A loader was added while disabled; refusing to claim it"
            )
        old_hub = _file(paths.hub)
        if old_hub.data is not None and (
            _digest(old_hub.data) != receipt.get("hub_sha256")
            or old_hub.mode != receipt.get("hub_mode")
        ):
            raise RuntimeError(f"Changed hub config preserved: {paths.hub}")
        if hubs and (old_hub.data != hub or reseed):
            raise RuntimeError(
                "Stop the owned hub before changing its config or reseeding selections"
            )
    old_hub = _file(paths.hub)
    if old_hub.data != hub:
        planned.append(_Change(paths.hub, old_hub, hub))
    palette = _file(paths.palette)
    if palette.data is None:
        planned.append(_Change(paths.palette, palette, _PALETTE))
    elif not hubs and (
        _digest(palette.data) not in {receipt.get("palette_sha256"), _digest(_PALETTE)}
        or palette.mode != receipt.get("palette_mode")
    ):
        raise RuntimeError(f"Changed generated palette preserved: {paths.palette}")
    if receipt.get("enabled") is not True:
        separator = b"" if not config.data or config.data.endswith(b"\n") else b"\n"
        receipt["loader_separator"] = separator.decode()
        planned.append(
            _Change(paths.config, config, config.data + separator + loader, True)
        )
    selected, entries = _selection(paths)
    if not paths.receipt.exists() or reseed:
        _validate_files(paths)
        seeded = _seed(setup, paths, tools, entries)
        if selected.data != seeded:
            planned.append(_Change(paths.state / "plugins.json", selected, seeded))
    receipt["enabled"] = True
    receipt["hub_sha256"] = _digest(hub)
    receipt["hub_mode"] = old_hub.mode
    receipt["palette_mode"] = palette.mode
    receipt["palette_sha256"] = _digest(
        palette.data if palette.data is not None else _PALETTE
    )
    try:
        paths.workspace.mkdir(parents=True, exist_ok=True)
        paths.state.mkdir(exist_ok=True)
    except OSError as exc:
        raise RuntimeError(f"Cannot create owned setup workspace: {exc}") from exc
    with _operation_lock(paths):
        if _file(paths.receipt) != receipt_before:
            raise RuntimeError(
                "Setup ownership changed during apply; inspect before trying again"
            )
        _apply_changes(setup, paths, planned, receipt, receipt_before)
    return {
        "state": "applied",
        "server": setup.server,
        "reseeded": reseed,
        "changed": [str(change.path) for change in planned],
    }


def _events(paths: _Paths) -> list[dict[str, object]]:
    """Read only a bounded suffix; ignore an incomplete append, never malformed complete JSON."""
    path = paths.state / "events.jsonl"
    try:
        with path.open("rb") as stream:
            size = stream.seek(0, os.SEEK_END)
            offset = max(0, size - _MAX_READ)
            stream.seek(offset)
            data = stream.read(_MAX_READ)
    except FileNotFoundError:
        return []
    except OSError as exc:
        raise RuntimeError(f"Cannot read hub events: {exc}") from exc
    if offset:
        _, _, data = data.partition(b"\n")
    lines = data.split(b"\n")[:-1]
    return [_decode(line, "complete hub event") for line in lines if line]


def _selection_state(paths: _Paths) -> dict[str, object]:
    _, entries = _selection(paths)
    source = str(paths.project / "plugins" / "files")
    selected = False
    for item in entries:
        entry = _object(item, "managed plugin selection")
        if entry.get("id") == "files":
            if entry.get("source") != source:
                raise RuntimeError(
                    "Managed Files source changed; inspect the upstream manager selection"
                )
            selected = True
    if not selected:
        return {"state": "disabled", "reason": "removed"}
    database = paths.state / "hub.db"
    if not database.exists():
        return {"state": "starting", "reason": "selected"}
    try:
        with closing(
            sqlite3.connect(database.as_uri() + "?mode=ro", uri=True, timeout=1)
        ) as connection:
            connection.execute("PRAGMA query_only=ON")
            row = connection.execute(
                "SELECT desired, instance_id FROM plugins WHERE name = ?",
                ("rexdeck_files",),
            ).fetchone()
    except sqlite3.Error as exc:
        raise RuntimeError(f"Cannot read upstream Files desired state: {exc}") from exc
    if row is not None and row[0] == "stopped":
        return {"state": "disabled", "reason": "stopped by upstream manager"}
    return {"state": "starting", "instance_id": str(row[1]) if row else ""}


def _feature(
    setup: Setup, paths: _Paths, hub: _Hub, receipt: dict[str, object]
) -> dict[str, object]:
    listing = _rex(setup, "-C", hub.client, "do", "hub.plugins")
    entries = [
        _object(item, "hub plugin entry")
        for item in _list(listing.get("entries"), "hub plugin entries")
    ]
    files = [entry for entry in entries if entry.get("managed") == "files"]
    if not files:
        return {"state": "disabled", "reason": "removed"}
    if len(files) != 1:
        raise RuntimeError("Ambiguous managed Files entries")
    entry = files[0]
    if entry.get("source") != str(paths.project / "plugins" / "files"):
        raise RuntimeError("Running Files selection has another source")
    if entry.get("desired") == "stopped":
        return {"state": "disabled", "reason": "stopped by upstream manager"}
    if entry.get("state") in {"refused", "retained", "conflict"} or entry.get("error"):
        return {"state": "failed", "reason": entry.get("error", entry.get("state"))}
    instance = entry.get("instance_id")
    events = _events(paths)
    started = any(
        event.get("event") == "hub_started"
        and event.get("pid") == hub.pid
        and event.get("client_id") == hub.client
        and event.get("generation") == hub.generation
        for event in events
    )
    registered = (
        started
        and isinstance(instance, str)
        and bool(instance)
        and any(
            event.get("event") == "plugin_registered"
            and event.get("plugin") == "rexdeck_files"
            and event.get("instance_id") == instance
            and event.get("generation") == hub.generation
            for event in events
        )
    )
    evidence = receipt.get("readiness")
    if isinstance(evidence, dict):
        previous = _object(evidence, "saved readiness evidence")
        registered = registered or (
            previous.get("pid") == hub.pid
            and previous.get("client_id") == hub.client
            and previous.get("generation") == hub.generation
            # Once this exact hub generation has event-backed proof, its live registry
            # authoritatively identifies later instances too. Never use old events
            # to override the live registered flag.
            and isinstance(instance, str)
            and bool(instance)
        )
    ready = (
        entry.get("name") == "rexdeck_files"
        and entry.get("registered") is True
        and registered
    )
    return {
        "state": "feature-ready" if ready else "starting",
        "instance_id": instance,
        "generation": hub.generation,
    }


def status(setup: Setup) -> dict[str, object]:
    paths = _paths(setup)
    receipt = _receipt(paths, setup)
    if receipt is None or receipt.get("enabled") is not True:
        conflicts = receipt.get("conflicts", []) if receipt else []
        return {
            "state": "conflict" if conflicts else "disabled",
            "server": setup.server,
            "feature": {"state": "disabled"},
            "conflicts": conflicts,
        }
    _owned_config(paths, receipt)
    hubs = _hubs(setup, paths, receipt)
    if not hubs:
        pid = _verified_pid(receipt)
        feature = _selection_state(paths)
        return {
            "state": "starting" if pid else "stopped",
            "server": setup.server,
            "pid": pid,
            "feature": feature,
        }
    hub = hubs[0]
    feature = _feature(setup, paths, hub, receipt)
    state = "feature-ready" if feature["state"] == "feature-ready" else "host-ready"
    if feature["state"] == "failed":
        state = "failed"
    return {
        "state": state,
        "server": setup.server,
        "pid": hub.pid,
        "client_id": hub.client,
        "generation": hub.generation,
        "feature": feature,
    }


@contextmanager
def _operation_lock(paths: _Paths) -> Iterator[None]:
    try:
        descriptor = os.open(
            paths.workspace / "lifecycle.lock",
            os.O_CREAT | os.O_RDWR | os.O_NOFOLLOW,
            0o600,
        )
        with os.fdopen(descriptor, "r+b") as stream:
            try:
                fcntl.flock(stream.fileno(), fcntl.LOCK_EX | fcntl.LOCK_NB)
            except BlockingIOError as exc:
                raise RuntimeError(
                    "Another RexDeck lifecycle operation is in progress; inspect status"
                ) from exc
            try:
                yield
            finally:
                fcntl.flock(stream.fileno(), fcntl.LOCK_UN)
    except OSError as exc:
        raise RuntimeError(f"Cannot lock the owned lifecycle operation: {exc}") from exc


def start(setup: Setup) -> dict[str, object]:
    paths = _paths(setup)
    receipt = _receipt(paths, setup)
    if receipt is None or receipt.get("enabled") is not True:
        raise RuntimeError(
            "RexDeck is disabled or not applied; explicitly apply before starting"
        )
    _hubs(setup, paths, receipt)
    with _operation_lock(paths):
        return _start(setup)


def _start(setup: Setup) -> dict[str, object]:
    paths = _paths(setup)
    receipt_before = _file(paths.receipt)
    receipt = _receipt(paths, setup)
    if receipt is None or receipt.get("enabled") is not True:
        raise RuntimeError(
            "RexDeck is disabled or not applied; explicitly apply before starting"
        )
    _owned_config(paths, receipt)
    runtime = verify_runtime(paths.project, paths.workspace)
    tools = _tools()
    if _file(paths.hub).data != _hub_config(setup, paths, runtime, tools):
        raise RuntimeError(
            "Prepared runtime or tool paths changed; inspect and reapply before starting"
        )
    _check(setup)
    hubs = _hubs(setup, paths, receipt)
    if hubs:
        return status(setup)
    if _selection_state(paths)["state"] != "disabled":
        _validate_files(paths)
    if _verified_pid(receipt) is not None:
        raise RuntimeError(
            "Owned hub process is already starting or disconnected; inspect status, do not start a competitor"
        )
    palette = _file(paths.palette)
    if _digest(palette.data) not in {
        receipt.get("palette_sha256"),
        _digest(_PALETTE),
    } or palette.mode != receipt.get("palette_mode"):
        raise RuntimeError(
            "Generated palette changed while stopped; reconcile it before starting"
        )
    argv = [str(runtime.hub), "-config", str(paths.hub), "-sdk", str(runtime.sdk)]
    if setup.real_server:
        argv.append("-real-server")
    # SIGINT may land inside Popen after the detached child exists but before
    # Python assigns its handle. Defer it until ownership or exact-child cleanup.
    with _defer_sigint():
        try:
            with (paths.workspace / "process.log").open("ab") as log:
                child = subprocess.Popen(
                    argv,
                    env=_env(setup),
                    stdin=subprocess.DEVNULL,
                    stdout=log,
                    stderr=log,
                    start_new_session=True,
                )
        except OSError as exc:
            raise RuntimeError(f"Cannot start the prepared hub: {exc}") from exc
        try:
            identity = _process(child.pid)
            if identity is None or not identity.endswith(" ".join(argv)):
                raise RuntimeError(
                    f"Started hub identity could not be captured: PID {child.pid}"
                )
            receipt["launch"] = {"pid": child.pid, "identity": identity, "argv": argv}
            _replace(paths.receipt, receipt_before, _json(receipt))
        except (RuntimeError, OSError, KeyboardInterrupt) as exc:
            try:
                child.terminate()
                child.wait(timeout=_STOP_WAIT)
            except (OSError, subprocess.TimeoutExpired) as cleanup_error:
                message = (
                    f"Launch receipt failed and child {child.pid} did not terminate; "
                    "inspect process.log"
                )
                if isinstance(exc, KeyboardInterrupt):
                    exc.add_note(message)
                    raise exc from cleanup_error
                raise RuntimeError(message) from cleanup_error
            raise
    receipt_before = _file(paths.receipt)
    deadline = time.monotonic() + _START_WAIT
    while time.monotonic() < deadline:
        if child.poll() is not None:
            raise RuntimeError(
                f"Owned hub exited {child.returncode}; inspect {paths.workspace / 'process.log'}"
            )
        result = status(setup)
        feature = _object(result.get("feature"), "Files readiness")
        if result["state"] == "failed":
            raise RuntimeError(
                f"Files failed: {feature.get('reason')}; hub left running for inspection"
            )
        if result["state"] == "feature-ready" or (
            result["state"] == "host-ready" and feature["state"] == "disabled"
        ):
            if not any(
                event.get("event") == "hub_started"
                and event.get("pid") == result["pid"]
                and event.get("client_id") == result["client_id"]
                and event.get("generation") == result["generation"]
                for event in _events(paths)
            ):
                time.sleep(0.1)
                continue
            receipt["palette_sha256"] = _digest(_file(paths.palette).data)
            receipt["palette_mode"] = _file(paths.palette).mode
            receipt["readiness"] = {
                "pid": result["pid"],
                "client_id": result["client_id"],
                "generation": result["generation"],
                "instance_id": feature.get("instance_id"),
            }
            _replace(paths.receipt, receipt_before, _json(receipt))
            return result
        time.sleep(0.1)
    raise RuntimeError(
        f"Owned hub/selected Files did not become ready in {_START_WAIT:g}s; inspect process.log and hub-state/events.jsonl; hub left intact"
    )


def _finish_stop(paths: _Paths, receipt: dict[str, object], before: _File) -> list[str]:
    palette = _file(paths.palette)
    conflicts: list[str] = []
    if palette.data == _PALETTE and palette.mode in {
        receipt.get("palette_mode"),
        0o644,
    }:
        receipt["palette_sha256"] = _digest(_PALETTE)
        receipt["palette_mode"] = palette.mode
    elif _digest(palette.data) != receipt.get(
        "palette_sha256"
    ) or palette.mode != receipt.get("palette_mode"):
        conflicts.append(f"Changed generated palette preserved: {paths.palette}")
    receipt["launch"] = None
    _replace(paths.receipt, before, _json(receipt))
    return conflicts


def stop(setup: Setup) -> dict[str, object]:
    paths = _paths(setup)
    receipt = _receipt(paths, setup)
    if receipt is None:
        _hubs(setup, paths, None)
        return {"state": "stopped", "server": setup.server}
    _hubs(setup, paths, receipt)
    with _operation_lock(paths):
        return _stop(setup)


def _stop(setup: Setup) -> dict[str, object]:
    paths = _paths(setup)
    receipt_before = _file(paths.receipt)
    receipt = _receipt(paths, setup)
    if receipt is None:
        _hubs(setup, paths, None)
        return {"state": "stopped", "server": setup.server}
    # Discovery and process identity are checked before any shutdown request or signal.
    hubs = _hubs(setup, paths, receipt)
    pid = _verified_pid(receipt)
    if pid is None:
        conflicts = (
            _finish_stop(paths, receipt, receipt_before) if _launch(receipt) else []
        )
        return {"state": "stopped", "server": setup.server, "conflicts": conflicts}
    if hubs:
        _rex(setup, "-C", hubs[0].client, "do", "hub.admin.shutdown")
    else:
        # A not-yet-connected owned child still needs an orderly SIGTERM (never a group kill).
        if _verified_pid(receipt) != pid:
            raise RuntimeError("Hub identity changed immediately before stop")
        try:
            os.kill(pid, signal.SIGTERM)
        except ProcessLookupError:
            return {"state": "stopped", "server": setup.server}
        except OSError as exc:
            raise RuntimeError(f"Cannot stop verified owned hub {pid}: {exc}") from exc
    launch = _launch(receipt)
    assert launch is not None
    identity = launch["identity"]
    deadline = time.monotonic() + _STOP_WAIT
    while time.monotonic() < deadline:
        if _process(pid) != identity:
            # Absence or another start identity proves the original writer has terminated.
            conflicts = _finish_stop(paths, receipt, receipt_before)
            return {"state": "stopped", "server": setup.server, "conflicts": conflicts}
        time.sleep(0.1)
    raise RuntimeError(
        f"Owned hub {pid} did not terminate within {_STOP_WAIT:g}s; palette left untouched"
    )


def disable(setup: Setup) -> dict[str, object]:
    paths = _paths(setup)
    receipt = _receipt(paths, setup)
    if receipt is None:
        _hubs(setup, paths, None)
        return {"state": "disabled", "server": setup.server, "conflicts": []}
    _hubs(setup, paths, receipt)
    with _operation_lock(paths):
        return _disable(setup)


def _disable(setup: Setup) -> dict[str, object]:
    paths = _paths(setup)
    receipt = _receipt(paths, setup)
    _stop(
        setup
    )  # Hold the operation lock until the writer and its artifacts are reconciled.
    if receipt is None:
        return {"state": "disabled", "server": setup.server, "conflicts": []}
    receipt = _receipt(paths, setup)
    assert receipt is not None
    receipt_before = _file(paths.receipt)
    conflicts: list[str] = []
    if receipt.get("enabled") is not True:
        stale = [
            str(path)
            for path in (paths.hub, paths.palette)
            if _file(path).data is not None
        ]
        conflicts = [
            f"Disabled setup retains changed artifact: {path}" for path in stale
        ]
        if receipt.get("conflicts") != conflicts:
            receipt["conflicts"] = conflicts
            _replace(paths.receipt, receipt_before, _json(receipt))
        return {
            "state": "conflict" if stale else "disabled",
            "server": setup.server,
            "conflicts": conflicts,
        }
    current = _file(paths.config)
    assert current.data is not None
    loader = _loader(paths)
    try:
        restored = _without_loader(
            current.data,
            loader,
            remove_separator=receipt.get("loader_separator") == "\n",
        )
    except RuntimeError as exc:
        return {"state": "conflict", "server": setup.server, "conflicts": [str(exc)]}
    palette = _file(paths.palette)
    removable_palette = palette.data is None or (
        (
            _digest(palette.data) == receipt.get("palette_sha256")
            or palette.data == _PALETTE
        )
        and palette.mode == receipt.get("palette_mode")
    )
    if not removable_palette:
        conflicts.append(f"Changed generated palette preserved: {paths.palette}")
    hub = _file(paths.hub)
    removable_hub = hub.data is None or (
        _digest(hub.data) == receipt.get("hub_sha256")
        and hub.mode == receipt.get("hub_mode")
    )
    if not removable_hub:
        conflicts.append(f"Changed hub config preserved: {paths.hub}")
    changes: list[_Change] = [_Change(paths.config, current, restored, True)]
    if removable_palette and palette.data is not None:
        changes.append(_Change(paths.palette, palette, None))
    if removable_hub and hub.data is not None:
        changes.append(_Change(paths.hub, hub, None))
    applied: list[_Change] = []
    try:
        for change in changes:
            if paths.selected.resolve(strict=True) != paths.config:
                raise RuntimeError("Selected Rex config symlink changed during disable")
            applied.append(change)
            _replace(change.path, change.before, change.after)
        _check(setup)
        _reload(setup)
        receipt["enabled"] = False
        receipt["launch"] = None
        receipt["conflicts"] = conflicts
        publication = _Change(paths.receipt, receipt_before, _json(receipt))
        applied.append(publication)
        _replace(publication.path, publication.before, publication.after)
    except (RuntimeError, OSError, KeyboardInterrupt) as exc:
        _recover_changes(setup, applied, "Disable", exc)
    return {
        "state": "conflict" if conflicts else "disabled",
        "server": setup.server,
        "conflicts": conflicts,
        "preserved_state": str(paths.state),
    }
